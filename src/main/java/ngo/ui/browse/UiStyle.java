/**
 * Shared visual style, role-aware left navigation, user box (change password / log out) and helpers used by ALL screens,
 * so that every window of the application looks and behaves the same.
 */
public final class UiStyle {
    public static final Color SIDEBAR_BG = new Color(0xF7F7F5);
    public static final Color LINE = new Color(0xE5E5E5);
    public static final Color TEXT = new Color(0x1A1A1A);
    public static final Color MUTED = new Color(0x5F5E5A);
    public static final Color SELECT_BG = new Color(0xE6F1FB);
    public static final Color SELECT_FG = new Color(0x0C447C);
    public static final Color ACCENT = new Color(0x185FA5);
    public static final Color DANGER = new Color(0xA32D2D);
    public static final Font FONT = new Font("Segoe UI", Font.PLAIN, 13);
    public static final Font FONT_BOLD = new Font("Segoe UI", Font.BOLD, 14);
    public static final Font FONT_TITLE = new Font("Segoe UI", Font.BOLD, 20);
    static final int SIDEBAR_WIDTH = 170;

    private UiStyle() { }

    /** Menu items visible for a role (users never see the editing screens). */
    public static String[] menuFor(Role role) {
        if (role != null && role.isStaff())
            return new String[]{"Home", "Browse", "Search tasks", "Projects", "My tasks", "Edit task", "Manage", "Report"};
        return new String[]{"Home", "Browse", "Search tasks", "Projects", "My tasks", "Report"};
    }

    /** Adds the common left sidebar and the common theme to a screen. */
    public static void apply(JFrame frame, String activeMenu) {
        // Screens generated by NetBeans use GroupLayout: wrap their content in BorderLayout first.
        if (!(frame.getContentPane().getLayout() instanceof BorderLayout)) {
            Container oldContent = frame.getContentPane();
            JPanel wrapper = new JPanel(new BorderLayout());
            wrapper.setBackground(Color.WHITE);
            frame.setContentPane(wrapper);
            wrapper.add(oldContent, BorderLayout.CENTER);
        }
        frame.getContentPane().setBackground(Color.WHITE);
        style(frame.getContentPane());
        theme(frame.getContentPane());
        frame.getContentPane().add(createSidebar(activeMenu, frame), BorderLayout.WEST);
        frame.setTitle("NGO Tasks - " + activeMenu);
        frame.setSize(1200, 700);
        frame.setMinimumSize(new Dimension(1050, 650));
        frame.setLocationRelativeTo(null);
    }

    private static void style(Container container) {
        for (Component component : container.getComponents()) {
            if (component instanceof JTable || component instanceof JTableHeader) continue;
            if (component instanceof JPanel) {
                component.setBackground(Color.WHITE);
            } else if (component instanceof JLabel) {
                component.setFont(FONT_BOLD);
                component.setForeground(TEXT);
            }
            if (component instanceof Container) style((Container) component);
        }
    }

    /**
     * Recursive theme: plain JButtons become flat blue buttons, tables use styleTable, tabs/combos/scroll panes share
     * the fonts and borders. Buttons that already paint themselves (RoundButton etc.) are left alone.
     */
    public static void theme(Container container) {
        for (Component c : container.getComponents()) {
            if (c instanceof JButton && c.getClass() == JButton.class) styleButton((JButton) c, false);
            else if (c instanceof JTable) styleTable((JTable) c);
            else if (c instanceof JTabbedPane) c.setFont(FONT);
            else if (c instanceof JComboBox) c.setFont(FONT);
            else if (c instanceof JScrollPane) ((JScrollPane) c).setBorder(BorderFactory.createLineBorder(LINE));
            if (c instanceof Container) theme((Container) c);
        }
    }

    /** Flat button: blue fill (primary) or white with a grey line (secondary). */
    public static void styleButton(AbstractButton b, boolean secondary) {
        b.setUI(new BasicButtonUI());
        b.setFont(FONT);
        b.setOpaque(true);
        b.setFocusPainted(false);
        b.setContentAreaFilled(true);
        b.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
        b.setBackground(secondary ? Color.WHITE : ACCENT);
        b.setForeground(secondary ? TEXT : Color.WHITE);
        b.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(secondary ? LINE : ACCENT),
                BorderFactory.createEmptyBorder(6, 14, 6, 14)));
    }

    public static void styleTable(JTable table) {
        table.setFont(FONT);
        table.setRowHeight(34);
        table.setShowVerticalLines(false);
        table.setShowHorizontalLines(true);
        table.setGridColor(LINE);
        table.setSelectionBackground(SELECT_BG);
        table.setSelectionForeground(SELECT_FG);
        table.setFillsViewportHeight(true);
        table.setDefaultRenderer(Object.class, new StatusCellRenderer());
        JTableHeader header = table.getTableHeader();
        header.setReorderingAllowed(false);
        header.setPreferredSize(new Dimension(100, 36));
        header.setDefaultRenderer(new HeaderCellRenderer());
    }

    /** Runs a database call off the Swing thread; errors are shown in a dialog with the same message style everywhere. */
    public static <T> void async(Component parent, Callable<T> work, Consumer<T> onSuccess) {
        new SwingWorker<T, Void>() {
            @Override protected T doInBackground() throws Exception { return work.call(); }
            @Override protected void done() {
                try {
                    onSuccess.accept(get());
                } catch (java.util.concurrent.ExecutionException ex) {
                    showError(parent, ex.getCause());
                } catch (InterruptedException ex) {
                    Thread.currentThread().interrupt();
                }
            }
        }.execute();
    }

    public static void showError(Component parent, Throwable t) {
        String msg = (t instanceof DataAccessException || t instanceof IllegalArgumentException)
                ? t.getMessage() : "Unexpected error. Please try again.";
        JOptionPane.showMessageDialog(parent, msg, "Error", JOptionPane.ERROR_MESSAGE);
    }

    private static JPanel createSidebar(String active, JFrame currentFrame) {
        JPanel panel = new JPanel();
        panel.setLayout(new BoxLayout(panel, BoxLayout.Y_AXIS));
        panel.setBackground(SIDEBAR_BG);
        panel.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createMatteBorder(0, 0, 0, 1, LINE),
                BorderFactory.createEmptyBorder(16, 10, 16, 10)));
        panel.setPreferredSize(new Dimension(SIDEBAR_WIDTH, 600));

        JLabel brand = new JLabel("NGO Tasks");
        brand.setFont(new Font("Segoe UI", Font.BOLD, 16));
        brand.setForeground(TEXT);
        brand.setBorder(BorderFactory.createEmptyBorder(0, 8, 18, 0));
        brand.setAlignmentX(Component.LEFT_ALIGNMENT);
        panel.add(brand);

        AuthUser me = Session.user();
        for (String menuName : menuFor(me == null ? null : me.getRole())) {
            JLabel item = new JLabel(menuName);
            boolean selected = menuName.equals(active);
            item.setFont(FONT);
            item.setOpaque(true);
            item.setBackground(selected ? Color.WHITE : SIDEBAR_BG);
            item.setForeground(selected ? TEXT : MUTED);
            item.setBorder(BorderFactory.createEmptyBorder(0, 10, 0, 4));
            item.setAlignmentX(Component.LEFT_ALIGNMENT);
            item.setMaximumSize(new Dimension(SIDEBAR_WIDTH - 20, 36));
            item.setPreferredSize(new Dimension(SIDEBAR_WIDTH - 20, 36));
            item.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
            item.addMouseListener(new MouseAdapter() {
                @Override public void mouseClicked(MouseEvent event) { go(menuName, currentFrame); }
                @Override public void mouseEntered(MouseEvent event) {
                    if (!menuName.equals(active)) item.setBackground(new Color(0xEEEEEC));
                }
                @Override public void mouseExited(MouseEvent event) {
                    if (!menuName.equals(active)) item.setBackground(SIDEBAR_BG);
                }
            });
            panel.add(item);
            panel.add(Box.createVerticalStrut(4));
        }

        panel.add(Box.createVerticalGlue());
        if (me != null) panel.add(userBox(me, currentFrame));
        return panel;
    }

    private static JPanel userBox(AuthUser me, JFrame frame) {
        JPanel box = new JPanel(new GridLayout(0, 1, 0, 6));
        box.setBackground(SIDEBAR_BG);
        box.setAlignmentX(Component.LEFT_ALIGNMENT);
        box.setMaximumSize(new Dimension(SIDEBAR_WIDTH - 20, 150));

        JLabel name = new JLabel("<html><b>" + escape(me.getFullName()) + "</b></html>");
        name.setFont(FONT);
        name.setForeground(TEXT);
        JLabel role = new JLabel(me.getRole().label());
        role.setFont(new Font("Segoe UI", Font.BOLD, 11));
        role.setOpaque(true);
        role.setHorizontalAlignment(JLabel.CENTER);
        role.setForeground(Color.WHITE);
        role.setBackground(roleColor(me.getRole()));
        JButton pw = new JButton("Change password");
        styleButton(pw, true);
        pw.addActionListener(e -> changePassword(frame));
        JButton out = new JButton("Log out");
        styleButton(out, true);
        out.setForeground(DANGER);
        out.addActionListener(e -> logout());
        box.add(name);
        box.add(role);
        box.add(pw);
        box.add(out);
        return box;
    }

    public static Color roleColor(Role r) {
        switch (r) {
            case ADMIN: return new Color(0x791F1F);
            case MANAGER: return new Color(0x185FA5);
            default: return new Color(0x3B6D11);
        }
    }

    private static String escape(String s) {
        return s == null ? "" : s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }

    /** Closes every window and shows the log-in screen. */
    public static void logout() {
        AuthService.logout();
        for (Window w : Window.getWindows()) w.dispose();
        new LoginFrame().setVisible(true);
    }

    private static void changePassword(Component parent) {
        JPasswordField oldPw = new JPasswordField();
        JPasswordField newPw = new JPasswordField();
        JPasswordField again = new JPasswordField();
        Object[] form = {"Old password", oldPw, "New password (at least 8 characters)", newPw, "Repeat new password", again};
        if (JOptionPane.showConfirmDialog(parent, form, "Change password",
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE) != JOptionPane.OK_OPTION) return;
        String o = new String(oldPw.getPassword());
        String n = new String(newPw.getPassword());
        if (!n.equals(new String(again.getPassword()))) {
            JOptionPane.showMessageDialog(parent, "The two new passwords are not the same.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        async(parent, () -> { AuthService.changePassword(o, n); return Boolean.TRUE; },
                ok -> JOptionPane.showMessageDialog(parent, "Password changed.", "NGO Tasks", JOptionPane.INFORMATION_MESSAGE));
    }

    /** Opens the screen of a menu item and closes the current one. */
    public static void go(String menuName, JFrame currentFrame) {
        if (!Session.isLoggedIn()) return;
        String current = currentFrame.getTitle();
        if (current != null && current.equals("NGO Tasks - " + menuName)) return;
        JFrame nextFrame;
        try {
            switch (menuName) {
                case "Home": nextFrame = new ngo.ui.MainFrame(); break;
                case "Browse": nextFrame = new ngo.ui.grid.BrowseForm(); break;
                case "Search tasks": nextFrame = new SearchForm(); break;
                case "Projects": nextFrame = new MasterDetailForm(); break;
                case "My tasks": nextFrame = new ngo.ui.MyTasksForm(); break;
                case "Edit task": nextFrame = new ngo.ui.edit.EditTaskForm(); break;
                case "Manage": nextFrame = new ngo.ui.ManageFrame(); break;
                case "Report": nextFrame = new ngo.ui.report.ReportForm(); break;
                default: return;
            }
        } catch (RuntimeException ex) {
            showError(currentFrame, ex);
            return;
        }
        nextFrame.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
        nextFrame.setLocationRelativeTo(currentFrame);
        nextFrame.setVisible(true);
        currentFrame.dispose();
    }

    private static final class StatusCellRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable table, Object value,
                                                       boolean selected, boolean focused,
                                                       int row, int column) {
            super.getTableCellRendererComponent(table, value, selected, false, row, column);
            setBorder(BorderFactory.createEmptyBorder(0, 10, 0, 10));
            setOpaque(true);
            if (selected) {
                setBackground(SELECT_BG);
                setForeground(SELECT_FG);
                return this;
            }
            setBackground(Color.WHITE);
            setForeground(TEXT);
            String text = value == null ? "" : value.toString();
            switch (text) {
                case "DONE":
                    setBackground(new Color(0xEAF3DE));
                    setForeground(new Color(0x27500A));
                    break;
                case "IN_PROGRESS":
                    setBackground(new Color(0xE6F1FB));
                    setForeground(new Color(0x0C447C));
                    break;
                case "TODO":
                    setBackground(new Color(0xF1EFE8));
                    setForeground(new Color(0x444441));
                    break;
                case "CANCELLED":
                    setBackground(new Color(0xFCEBEB));
                    setForeground(new Color(0x791F1F));
                    break;
                case "URGENT":
                    setForeground(new Color(0xA32D2D));
                    break;
                default:
                    break;
            }
            return this;
        }
    }

    private static final class HeaderCellRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable table, Object value,
                                                       boolean selected, boolean focused,
                                                       int row, int column) {
            super.getTableCellRendererComponent(table, value, false, false, row, column);
            setOpaque(true);
            setBackground(SIDEBAR_BG);
            setForeground(MUTED);
            setFont(new Font("Segoe UI", Font.PLAIN, 12));
            setHorizontalAlignment(LEFT);
            setBorder(BorderFactory.createCompoundBorder(
                    BorderFactory.createMatteBorder(0, 0, 1, 0, LINE),
                    BorderFactory.createEmptyBorder(0, 10, 0, 10)));
            return this;
        }
    }
}
