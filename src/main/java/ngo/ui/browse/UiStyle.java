package ngo.ui.browse;

import ngo.ui.edit.EditTaskForm;

import javax.swing.BorderFactory;
import javax.swing.Box;
import javax.swing.BoxLayout;
import javax.swing.JFrame;
import javax.swing.JLabel;
import javax.swing.JOptionPane;
import javax.swing.JPanel;
import javax.swing.JTable;
import javax.swing.table.DefaultTableCellRenderer;
import javax.swing.table.JTableHeader;
import java.awt.BorderLayout;
import java.awt.Color;
import java.awt.Component;
import java.awt.Container;
import java.awt.Cursor;
import java.awt.Dimension;
import java.awt.Font;
import java.awt.event.MouseAdapter;
import java.awt.event.MouseEvent;

/** Shared visual style and left navigation used by Projects and Edit Task screens. */
public final class UiStyle {
    static final Color SIDEBAR_BG = new Color(0xF7F7F5);
    static final Color LINE = new Color(0xE5E5E5);
    static final Color TEXT = new Color(0x1A1A1A);
    static final Color MUTED = new Color(0x5F5E5A);
    static final Color SELECT_BG = new Color(0xE6F1FB);
    static final Color SELECT_FG = new Color(0x0C447C);
    static final Font FONT = new Font("Segoe UI", Font.PLAIN, 13);
    static final Font FONT_BOLD = new Font("Segoe UI", Font.BOLD, 14);

    private UiStyle() { }

    /** Add the same 140px left sidebar used by the approved Projects screenshot. */
    public static void apply(JFrame frame, String activeMenu) {
        // SearchForm generated by NetBeans uses GroupLayout. Wrap its existing
        // content in BorderLayout before adding the common left sidebar.
        if (!(frame.getContentPane().getLayout() instanceof BorderLayout)) {
            Container oldContent = frame.getContentPane();
            JPanel wrapper = new JPanel(new BorderLayout());
            wrapper.setBackground(Color.WHITE);
            frame.setContentPane(wrapper);
            wrapper.add(oldContent, BorderLayout.CENTER);
        }
        frame.getContentPane().setBackground(Color.WHITE);
        style(frame.getContentPane());
        frame.getContentPane().add(createSidebar(activeMenu, frame), BorderLayout.WEST);
        frame.setSize(1200, 700);
        frame.setMinimumSize(new Dimension(1050, 650));
        frame.setLocationRelativeTo(null);
    }

    private static void style(Container container) {
        for (Component component : container.getComponents()) {
            if (component instanceof JTable || component instanceof JTableHeader) continue;
            if (component instanceof JPanel) {
                component.setBackground(Color.WHITE);
            } else if (component instanceof JLabel) {
                component.setFont(FONT_BOLD);
                component.setForeground(TEXT);
            }
            if (component instanceof Container) style((Container) component);
        }
    }

    public static void styleTable(JTable table) {
        table.setFont(FONT);
        table.setRowHeight(34);
        table.setShowVerticalLines(false);
        table.setShowHorizontalLines(true);
        table.setGridColor(LINE);
        table.setSelectionBackground(SELECT_BG);
        table.setSelectionForeground(SELECT_FG);
        table.setFillsViewportHeight(true);
        table.setDefaultRenderer(Object.class, new StatusCellRenderer());
        JTableHeader header = table.getTableHeader();
        header.setReorderingAllowed(false);
        header.setPreferredSize(new Dimension(100, 36));
        header.setDefaultRenderer(new HeaderCellRenderer());
    }

    private static JPanel createSidebar(String active, JFrame currentFrame) {
        JPanel panel = new JPanel();
        panel.setLayout(new BoxLayout(panel, BoxLayout.Y_AXIS));
        panel.setBackground(SIDEBAR_BG);
        panel.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createMatteBorder(0, 0, 0, 1, LINE),
                BorderFactory.createEmptyBorder(16, 10, 16, 10)));
        panel.setPreferredSize(new Dimension(140, 600));

        JLabel brand = new JLabel("NGO Tasks");
        brand.setFont(new Font("Segoe UI", Font.BOLD, 16));
        brand.setForeground(TEXT);
        brand.setBorder(BorderFactory.createEmptyBorder(0, 8, 18, 0));
        brand.setAlignmentX(Component.LEFT_ALIGNMENT);
        panel.add(brand);

        String[] menuNames = {"Browse", "Search tasks", "Projects", "Edit task", "Report"};
        for (String menuName : menuNames) {
            JLabel item = new JLabel(menuName);
            boolean selected = menuName.equals(active);
            item.setFont(FONT);
            item.setOpaque(true);
            item.setBackground(selected ? Color.WHITE : SIDEBAR_BG);
            item.setForeground(selected ? TEXT : MUTED);
            item.setBorder(BorderFactory.createEmptyBorder(0, 10, 0, 4));
            item.setAlignmentX(Component.LEFT_ALIGNMENT);
            item.setMaximumSize(new Dimension(120, 36));
            item.setPreferredSize(new Dimension(120, 36));
            item.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
            item.addMouseListener(new MouseAdapter() {
                @Override public void mouseClicked(MouseEvent event) {
                    navigate(menuName, currentFrame);
                }
                @Override public void mouseEntered(MouseEvent event) {
                    if (!menuName.equals(active)) item.setBackground(new Color(0xEEEEEC));
                }
                @Override public void mouseExited(MouseEvent event) {
                    if (!menuName.equals(active)) item.setBackground(SIDEBAR_BG);
                }
            });
            panel.add(item);
            panel.add(Box.createVerticalStrut(4));
        }
        return panel;
    }

    private static void navigate(String menuName, JFrame currentFrame) {
        if (("Search tasks".equals(menuName) && currentFrame instanceof SearchForm)
                || ("Projects".equals(menuName) && currentFrame instanceof MasterDetailForm)
                || ("Edit task".equals(menuName) && currentFrame instanceof EditTaskForm)) {
            return;
        }

        JFrame nextFrame = null;
        switch (menuName) {
            case "Search tasks":
                nextFrame = new SearchForm();
                break;
            case "Projects":
                nextFrame = new MasterDetailForm();
                break;
            case "Edit task":
                nextFrame = new EditTaskForm();
                break;
            case "Browse":
                JOptionPane.showMessageDialog(currentFrame,
                        "Browse screen is managed by the Browse module.",
                        "NGO Tasks", JOptionPane.INFORMATION_MESSAGE);
                return;
            case "Report":
                JOptionPane.showMessageDialog(currentFrame,
                        "Report screen is managed by the Report module.",
                        "NGO Tasks", JOptionPane.INFORMATION_MESSAGE);
                return;
            default:
                return;
        }
        nextFrame.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
        nextFrame.setLocationRelativeTo(currentFrame);
        nextFrame.setVisible(true);
        currentFrame.dispose();
    }

    private static final class StatusCellRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable table, Object value,
                                                       boolean selected, boolean focused,
                                                       int row, int column) {
            super.getTableCellRendererComponent(table, value, selected, false, row, column);
            setBorder(BorderFactory.createEmptyBorder(0, 10, 0, 10));
            setOpaque(true);
            if (selected) {
                setBackground(SELECT_BG);
                setForeground(SELECT_FG);
                return this;
            }
            setBackground(Color.WHITE);
            setForeground(TEXT);
            String text = value == null ? "" : value.toString();
            switch (text) {
                case "DONE":
                    setBackground(new Color(0xEAF3DE));
                    setForeground(new Color(0x27500A));
                    break;
                case "IN_PROGRESS":
                    setBackground(new Color(0xE6F1FB));
                    setForeground(new Color(0x0C447C));
                    break;
                case "TODO":
                    setBackground(new Color(0xF1EFE8));
                    setForeground(new Color(0x444441));
                    break;
                case "CANCELLED":
                    setBackground(new Color(0xFCEBEB));
                    setForeground(new Color(0x791F1F));
                    break;
                case "URGENT":
                    setForeground(new Color(0xA32D2D));
                    break;
                default:
                    break;
            }
            return this;
        }
    }

    private static final class HeaderCellRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable table, Object value,
                                                       boolean selected, boolean focused,
                                                       int row, int column) {
            super.getTableCellRendererComponent(table, value, false, false, row, column);
            setOpaque(true);
            setBackground(SIDEBAR_BG);
            setForeground(MUTED);
            setFont(new Font("Segoe UI", Font.PLAIN, 12));
            setHorizontalAlignment(LEFT);
            setBorder(BorderFactory.createCompoundBorder(
                    BorderFactory.createMatteBorder(0, 0, 1, 0, LINE),
                    BorderFactory.createEmptyBorder(0, 10, 0, 10)));
            return this;
        }
    }
}
